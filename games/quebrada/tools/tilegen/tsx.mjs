// town.tsx / buildings.tsx writer: deterministic, fixed property order.
import { TILES, COLS, ROWS, SIZE } from "./catalog.mjs";

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

/** Generic writer: { name, image (file name next to the tsx), tiles, cols, rows, size }. */
export function buildTsxFor({ name, image, tiles, cols, rows, size = SIZE }) {
  const lines = [];
  lines.push(`<?xml version="1.0" encoding="UTF-8"?>`);
  lines.push(`<!-- GENERATED by games/quebrada/tools/tilegen (make tiles). Do not edit by hand: edit catalog*.mjs and regenerate. -->`);
  lines.push(`<tileset version="1.10" tiledversion="1.10.2" name="${name}" tilewidth="${size}" tileheight="${size}" tilecount="${cols * rows}" columns="${cols}">`);
  lines.push(` <image source="${image}" width="${cols * size}" height="${rows * size}"/>`);
  for (const t of tiles) {
    lines.push(` <tile id="${t.id}">`);
    lines.push(`  <properties>`);
    lines.push(`   <property name="name" value="${esc(t.name)}"/>`);
    lines.push(`   <property name="layer" value="${t.layer}"/>`);
    if (t.surface) lines.push(`   <property name="surface" value="${t.surface}"/>`);
    if (t.solid) lines.push(`   <property name="solid" type="bool" value="true"/>`);
    if (t.sort_offset !== undefined) lines.push(`   <property name="sort_offset" type="int" value="${t.sort_offset}"/>`);
    lines.push(`  </properties>`);
    lines.push(` </tile>`);
  }
  lines.push(`</tileset>`);
  return lines.join("\n") + "\n";
}

export function buildTsx() {
  return buildTsxFor({ name: "town", image: "town.png", tiles: TILES, cols: COLS, rows: ROWS });
}
