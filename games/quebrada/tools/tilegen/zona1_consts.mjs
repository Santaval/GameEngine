function toLua(v, key) {
  if (typeof v === "number") { if (!Number.isFinite(v)) throw new Error(`zona1_consts: ${key} is not finite`); return String(v); }
  if (Array.isArray(v)) return `{ ${v.map((x) => toLua(x, key)).join(", ")} }`;
  if (v && typeof v === "object") return `{ ${Object.keys(v).sort().map((k) => `${k} = ${toLua(v[k], `${key}.${k}`)}`).join(", ")} }`;
  throw new Error(`zona1_consts: ${key} has an unsupported value (${typeof v})`);
}

export function buildZona1ConstsLua() {
  const lines = KEYS.slice().sort().map((k) => {
    if (!(k in M)) throw new Error(`zona1_consts: zona1_map.mjs does not export ${k}`);
    return `  ${k} = ${toLua(M[k], k)},`;
  });
  const b = M.BRIDGE; // numeric fields only
  lines.push(`  BRIDGE = { ${Object.keys(b).sort().map((k) => `${k} = ${toLua(b[k], `BRIDGE.${k}`)}`).join(", ")} },`);
  return `-- GENERATED by games/quebrada/tools/tilegen/gen.mjs (make tiles). Do not edit.\n-- Rows are in the ABSOLUTE frame (TOP_PAD included): subtract TOP_PAD to get the original frame used by zona1_check.lua's cell().\nreturn {\n${lines.join("\n")}\n}\n`;
}
